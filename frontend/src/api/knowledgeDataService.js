function buildArticles() {
  return RAW_ARTICLES.map((raw, idx) => {
    const id = idx + 1;
    const scamType = inferScamType(raw.title, raw.content);
    const threatLevel = inferThreatLevel(raw.title, raw.content);
    return {
      id,
      title: raw.title,
      content: raw.content,
      scamType,
      source: raw.source,
      createdAt: genDate(id),
      threatLevel,
      tags: scamType,
      attackTacticId: null,
    };
  });
}

let _localArticles = null;
function getLocalArticles() {
  if (!_localArticles) _localArticles = buildArticles();
  return _localArticles;
}

// ============================================================
// 分页 + 搜索 + 分类过滤（模拟 /api/knowledge/list）
// ============================================================
export function queryLocalKnowledge({ current = 1, size = 12, keyword = "", scamType = "" } = {}) {
  let articles = getLocalArticles();

  if (scamType && scamType !== "全部") {
    articles = articles.filter((a) => a.scamType === scamType);
  }

  if (keyword) {
    const kw = keyword.toLowerCase();
    articles = articles.filter(
      (a) =>
        a.title.toLowerCase().includes(kw) ||
        a.content.toLowerCase().includes(kw) ||
        a.scamType.includes(kw)
    );
  }

  const total = articles.length;
  const pages = Math.ceil(total / size);
  const start = (current - 1) * size;
  const records = articles.slice(start, start + size);

  return { records, total, pages, current, size };
}

// ============================================================
// 根据 ID 获取文章详情（模拟 /api/knowledge/:id）
// ============================================================
export function getLocalArticleById(id) {
  return getLocalArticles().find((a) => a.id === Number(id)) || null;
}

// ============================================================
// 获取相关文章（同类型前4条）
// ============================================================
export function getLocalRelatedArticles(articleId, limit = 4) {
  const articles = getLocalArticles();
  const target = articles.find((a) => a.id === Number(articleId));
  if (!target) return [];
  return articles
    .filter((a) => a.id !== Number(articleId) && a.scamType === target.scamType)
    .slice(0, limit);
}

