function inferScamType(title, content) {
  const text = title + content;
  for (const { keywords, type } of SCAM_TYPE_KEYWORDS) {
    for (const kw of keywords) {
      if (new RegExp(kw).test(text)) return type;
    }
  }
  return "其他";
}

function inferThreatLevel(title, content) {
  const text = title + content;
  if (/万元|百万|高危|紧急预警|重大/.test(text)) return 3;
  if (/千元|预警|警惕|警方提醒/.test(text)) return 2;
  return 1;
}

function genDate(id) {
  const base = new Date("2024-01-01");
  base.setDate(base.getDate() + (id * 7) % 365);
  return base.toISOString();
}

